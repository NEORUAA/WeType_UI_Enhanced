#!/usr/bin/env python3
"""Resolve keyboard SF Symbols by exact name and verify the bundled SF Pro cmap."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import struct
import subprocess


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CLI = Path("/Applications/SF Symbols Beta.app/Contents/Executables/sfsymbols")
SYMBOL_NAMES = (
    "arrow.left",
    "arrow.right",
    "arrow.turn.down.left",
    "arrow.up",
    "capslock",
    "capslock.fill",
    "checkmark",
    "delete.left",
    "delete.left.fill",
    "face.smiling",
    "face.smiling.inverse",
    "globe",
    "keyboard",
    "keyboard.chevron.compact.down",
    "magnifyingglass",
    "microphone",
    "paperplane.fill",
    "return",
    "return.left",
    "shift",
    "shift.fill",
)
ALIASES = {"mic": "microphone"}


def font_codepoints(path: Path) -> set[int]:
    data = path.read_bytes()
    table_count = struct.unpack_from(">H", data, 4)[0]
    for index in range(table_count):
        tag, _, offset, _ = struct.unpack_from(">4sIII", data, 12 + index * 16)
        if tag == b"cmap":
            break
    else:
        raise ValueError(f"No cmap table in {path}")
    count = struct.unpack_from(">H", data, offset + 2)[0]
    codepoints: set[int] = set()
    for index in range(count):
        _, _, subtable = struct.unpack_from(">HHI", data, offset + 4 + index * 8)
        subtable += offset
        if struct.unpack_from(">H", data, subtable)[0] != 12:
            continue
        groups = struct.unpack_from(">I", data, subtable + 12)[0]
        for group in range(groups):
            first, last, first_glyph = struct.unpack_from(">III", data, subtable + 16 + group * 12)
            codepoints.update(range(first + (first_glyph == 0), last + 1))
    if not codepoints:
        raise ValueError(f"No supplementary Unicode cmap in {path}")
    return codepoints


def resolve_symbol(cli: Path, name: str) -> int:
    for _ in range(3):
        result = subprocess.run(
            [str(cli), "search", "--match-style", "exactName", "--json", name],
            check=False, capture_output=True, text=True,
        )
        if result.returncode:
            continue
        try:
            records = json.loads(result.stdout)
        except json.JSONDecodeError:
            continue
        if len(records) == 1 and records[0].get("name") == name and records[0].get("codepoint"):
            return int(records[0]["codepoint"].removeprefix("U+"), 16)
        break
    raise ValueError(f"Unresolved SF Symbol: {name}")


def render_catalog(symbols: dict[str, int]) -> str:
    entries = "\n".join(f'        "{name}" to 0x{point:X},' for name, point in sorted(symbols.items()))
    return f'''// Generated by tools/generate_sf_symbol_catalog.py. Do not edit.
package com.xposed.wetypehook.wetype.graphics

internal object SfSymbolCatalog {{
    private val codePoints: Map<String, Int> = mapOf(
{entries}
    )
    private val glyphs: Map<String, String> = codePoints.mapValues {{ (_, point) ->
        String(Character.toChars(point))
    }}

    fun codePoint(systemName: String): Int? = codePoints[systemName]

    fun glyph(systemName: String): String? = glyphs[systemName]
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", type=Path, default=DEFAULT_CLI)
    parser.add_argument("--font", type=Path, default=ROOT / "app/src/main/assets/fonts/sf_pro.ttf")
    parser.add_argument(
        "--output", type=Path,
        default=ROOT / "app/src/main/java/com/xposed/wetypehook/wetype/graphics/SfSymbolCatalog.kt",
    )
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in catalog differs")
    args = parser.parse_args()
    if not args.cli.is_file():
        parser.error(f"SF Symbols CLI not found: {args.cli}")
    symbols = {name: resolve_symbol(args.cli, name) for name in SYMBOL_NAMES}
    available = font_codepoints(args.font)
    missing = [name for name, point in symbols.items() if point not in available]
    if missing:
        raise SystemExit("Bundled SF Pro is missing: " + ", ".join(missing))
    symbols.update({alias: symbols[canonical] for alias, canonical in ALIASES.items()})
    source = render_catalog(symbols)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != source:
            raise SystemExit(f"SF Symbol catalog is out of date: {args.output}")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source, encoding="utf-8")
    print(f"Verified {len(symbols)} SF Symbol mappings against {args.font.name}")


if __name__ == "__main__":
    main()
